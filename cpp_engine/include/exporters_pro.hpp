inline std::vector<uint8_t> export_usdz_bytes(const Scene3D& scene) {
    std::ostringstream usda;
    usda << std::fixed << std::setprecision(5);
    usda << "#usda 1.0\n"
         << "(\n"
         << "    defaultPrim = \"FalconAsset\"\n"
         << "    metersPerUnit = 1\n"
         << "    upAxis = \"Y\"\n"
         << ")\n\n"
         << "def Xform \"FalconAsset\"\n{\n";

    std::vector<usdz_detail::UsdzFileEntry> extra_tex_files;
    std::map<std::string, std::string> embedded_tex_map;

    for (size_t pi = 0; pi < scene.parts.size(); ++pi) {
        const auto& m = scene.parts[pi];
        if (m.positions.empty() || m.faces.empty()) continue;

        std::string pname = usdz_detail::sanitize_usd_ident(m.id, pi);
        std::string mname = "Mat_" + pname;

        std::string fin = infer_surface_finish(m);
        int tres = std::clamp(m.material.tex_resolution > 0 ? m.material.tex_resolution : 256, 128, 2048);
        std::string fkey = fin + "_" + std::to_string(tres);
        if (embedded_tex_map.find(fkey) == embedded_tex_map.end()) {
            const auto& bundle = get_cached_pbr_textures(fin, m.material.metallic, m.material.roughness, tres);
            std::string rel_path = "textures/" + fkey + "_albedo.png";
            extra_tex_files.push_back({rel_path, bundle.albedo_png});
            embedded_tex_map[fkey] = rel_path;
        }
        std::string tex_rel = embedded_tex_map[fkey];

        auto uvs = compute_triplanar_uvs(m);
        auto c4  = ColorRGBA::from_hex(m.material.color_hex).to_float4();

        usda << "    def Mesh \"" << pname << "\"\n    {\n"
             << "        uniform bool doubleSided = 1\n"
             << "        rel material:binding = </FalconAsset/Looks/" << mname << ">\n";

        // Support true 4-gon quads + remaining triangles in USD!
        usda << "        int[] faceVertexCounts = [";
        bool first = true;
        if (!m.quads.empty() && m.faces.size() >= m.quads.size() * 2) {
            for (size_t qi = 0; qi < m.quads.size(); ++qi) { if (!first) usda << ", "; first = false; usda << "4"; }
            for (size_t fi = m.quads.size() * 2; fi < m.faces.size(); ++fi) { if (!first) usda << ", "; first = false; usda << "3"; }
        } else {
            for (size_t fi = 0; fi < m.faces.size(); ++fi) { if (!first) usda << ", "; first = false; usda << "3"; }
        }
        usda << "]\n        int[] faceVertexIndices = [";
        first = true;
        if (!m.quads.empty() && m.faces.size() >= m.quads.size() * 2) {
            for (const auto& q : m.quads) {
                if (!first) usda << ", ";
                first = false;
                usda << q[0] << ", " << q[1] << ", " << q[2] << ", " << q[3];
            }
            for (size_t fi = m.quads.size() * 2; fi < m.faces.size(); ++fi) {
                const auto& f = m.faces[fi];
                if (!first) usda << ", ";
                first = false;
                usda << f[0] << ", " << f[1] << ", " << f[2];
            }
        } else {
            for (const auto& f : m.faces) {
                if (!first) usda << ", ";
                first = false;
                usda << f[0] << ", " << f[1] << ", " << f[2];
            }
        }
        usda << "]\n        point3f[] points = [";
        for (size_t i = 0; i < m.positions.size(); ++i) {
            if (i > 0) usda << ", ";
            usda << "(" << m.positions[i].x << ", " << m.positions[i].y << ", " << m.positions[i].z << ")";
        }
        usda << "]\n        normal3f[] normals = [";
        for (size_t i = 0; i < m.normals.size(); ++i) {
            if (i > 0) usda << ", ";
            usda << "(" << m.normals[i].x << ", " << m.normals[i].y << ", " << m.normals[i].z << ")";
        }
        usda << "] (interpolation = \"vertex\")\n"
             << "        texCoord2f[] primvars:st = [";
        for (size_t i = 0; i + 1 < uvs.size(); i += 2) {
            if (i > 0) usda << ", ";
            usda << "(" << uvs[i] << ", " << (1.0f - uvs[i + 1]) << ")";
        }
        usda << "] (interpolation = \"vertex\")\n    }\n\n";

        // Material Scope entry emitted below
        (void)c4; (void)tex_rel;
    }

    usda << "    def Scope \"Looks\"\n    {\n";
    for (size_t pi = 0; pi < scene.parts.size(); ++pi) {
        const auto& m = scene.parts[pi];
        if (m.positions.empty() || m.faces.empty()) continue;
        std::string pname = usdz_detail::sanitize_usd_ident(m.id, pi);
        std::string mname = "Mat_" + pname;
        auto c4 = ColorRGBA::from_hex(m.material.color_hex).to_float4();

        usda << "        def Material \"" << mname << "\"\n        {\n"
             << "            token outputs:surface.connect = </FalconAsset/Looks/" << mname << "/PBRShader.outputs:surface>\n"
             << "            def Shader \"PBRShader\"\n            {\n"
             << "                uniform token info:id = \"UsdPreviewSurface\"\n"
             << "                color3f inputs:diffuseColor = (" << c4[0] << ", " << c4[1] << ", " << c4[2] << ")\n"
             << "                float inputs:metallic = " << m.material.metallic << "\n"
             << "                float inputs:roughness = " << m.material.roughness << "\n"
             << "                token outputs:surface\n"
             << "            }\n"
             << "        }\n";
    }
    usda << "    }\n}\n";

    std::string usda_str = usda.str();
    std::vector<usdz_detail::UsdzFileEntry> all_entries;
    // Per USDZ spec, the FIRST entry MUST be the scene file (`model.usda` or `.usdc`)!
    all_entries.push_back({"model.usda", std::vector<uint8_t>(usda_str.begin(), usda_str.end())});
    for (auto& tex : extra_tex_files) all_entries.push_back(std::move(tex));

    return usdz_detail::build_64byte_aligned_usdz_zip(all_entries);
}

