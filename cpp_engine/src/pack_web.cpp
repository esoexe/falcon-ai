/**
 * OpenMesh Studio — Native C++20 Embedded VFS Asset Compiler (Replaces Docker Image Layers).
 * Compresses frontend/web_bundle/* with zlib level 9 and emits cpp_engine/include/embedded_web.hpp
 * so ./bin/openmesh_server compiles into a single standalone, zero-Docker executable.
 */

#include <algorithm>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>
#include <zlib.h>

namespace fs = std::filesystem;

namespace {

std::string guess_mime_pack(const fs::path& p) {
    std::string ext = p.extension().string();
    std::transform(ext.begin(), ext.end(), ext.begin(), ::tolower);
    if (ext == ".html") return "text/html; charset=utf-8";
    if (ext == ".js" || ext == ".mjs") return "application/javascript; charset=utf-8";
    if (ext == ".css") return "text/css; charset=utf-8";
    if (ext == ".svg") return "image/svg+xml";
    if (ext == ".png") return "image/png";
    if (ext == ".jpg" || ext == ".jpeg") return "image/jpeg";
    if (ext == ".json") return "application/json; charset=utf-8";
    return "application/octet-stream";
}

} // namespace

int main(int argc, char** argv) {
    fs::path web_dir = (argc > 1) ? fs::path(argv[1]) : fs::path("frontend/web_bundle");
    fs::path out_hdr = (argc > 2) ? fs::path(argv[2]) : fs::path("cpp_engine/include/embedded_web.hpp");

    if (!fs::exists(web_dir)) {
        std::cerr << "[pack_web] Error: " << web_dir << " does not exist.\n";
        return 1;
    }

    struct Entry {
        std::string url_path;
        std::string mime;
        size_t raw_size;
        std::vector<uint8_t> zbytes;
    };
    std::vector<Entry> entries;

    size_t total_raw = 0, total_comp = 0;
    for (const auto& de : fs::recursive_directory_iterator(web_dir)) {
        if (!de.is_regular_file()) continue;
        fs::path rel = fs::relative(de.path(), web_dir);
        std::string url_path = "/" + rel.generic_string();

        std::ifstream ifs(de.path(), std::ios::binary | std::ios::ate);
        size_t sz = static_cast<size_t>(ifs.tellg());
        ifs.seekg(0, std::ios::beg);
        std::vector<uint8_t> raw(sz);
        if (sz > 0) ifs.read(reinterpret_cast<char*>(raw.data()), static_cast<std::streamsize>(sz));

        uLongf dest_len = compressBound(static_cast<uLong>(sz));
        std::vector<uint8_t> comp(dest_len);
        if (compress2(comp.data(), &dest_len, raw.data(), static_cast<uLong>(sz), 9) != Z_OK) {
            std::cerr << "[pack_web] zlib compress2 failed for " << url_path << "\n";
            return 1;
        }
        comp.resize(dest_len);
        total_raw += sz;
        total_comp += dest_len;
        entries.push_back({url_path, guess_mime_pack(de.path()), sz, std::move(comp)});
    }

    std::ofstream out(out_hdr, std::ios::binary);
    out << "#pragma once\n"
        << "// AUTO-GENERATED BY cpp_engine/src/pack_web.cpp — DO NOT EDIT MANUALLY.\n"
        << "// Embeds the entire WebGL 3D Studio inside the C++20 executable (Zero Docker!).\n\n"
        << "#include <cstdint>\n#include <map>\n#include <string>\n#include <vector>\n#include <zlib.h>\n\n"
        << "namespace openmesh {\n\n"
        << "struct EmbeddedAsset {\n"
        << "    std::string mime;\n"
        << "    std::vector<uint8_t> bytes;\n"
        << "};\n\n";

    for (size_t idx = 0; idx < entries.size(); ++idx) {
        const auto& e = entries[idx];
        out << "static const uint8_t kWebAsset_" << idx << "[] = {";
        for (size_t b = 0; b < e.zbytes.size(); ++b) {
            if (b % 20 == 0) out << "\n    ";
            out << static_cast<unsigned int>(e.zbytes[b]);
            if (b + 1 < e.zbytes.size()) out << ",";
        }
        out << "\n};\n\n";
    }

    out << "inline std::map<std::string, EmbeddedAsset> load_embedded_web_vfs() {\n"
        << "    std::map<std::string, EmbeddedAsset> vfs;\n";

    for (size_t idx = 0; idx < entries.size(); ++idx) {
        const auto& e = entries[idx];
        out << "    {\n"
            << "        std::vector<uint8_t> raw(" << e.raw_size << ");\n"
            << "        uLongf dlen = " << e.raw_size << ";\n"
            << "        if (uncompress(raw.data(), &dlen, kWebAsset_" << idx << ", " << e.zbytes.size() << ") == Z_OK) {\n"
            << "            vfs[\"" << e.url_path << "\"] = {\"" << e.mime << "\", std::move(raw)};\n"
            << "        }\n"
            << "    }\n";
    }
    out << "    return vfs;\n"
        << "}\n\n"
        << "} // namespace openmesh\n";

    std::cout << "[pack_web] Embedded " << entries.size() << " WebGL studio files ("
              << (total_raw / 1024) << " KB -> " << (total_comp / 1024)
              << " KB zlib-9) into " << out_hdr << "\n";
    return 0;
}
